// Standalone export functions matching test_lore_overlay.mjs
export function showAnDuongVuongFourPartLore(chapterIdx = 0, options = {}) {
  if (typeof document === 'undefined') return null;

  if (typeof chapterIdx === 'number') {
    _currentChapterIdx = Math.max(0, Math.min(3, chapterIdx));
  } else if (typeof chapterIdx === 'string') {
    const key = chapterIdx.toLowerCase();
    if (LORE_DATA[key]?.chapterIndex !== undefined) {
      _currentChapterIdx = LORE_DATA[key].chapterIndex;
    }
  }

  _currentActiveTab = options.tab || 'chapters';

  let modal = createAnDuongVuongLoreOverlayDOM();
  if (!modal) return null;

  if (document.body) {
    if (!document.body.contains || !document.body.contains(modal)) {
      safeAppend(document.body, modal);
    }
  }

  try {
    if (document.exitPointerLock) {
      document.exitPointerLock();
    }
  } catch (err) {
    // pointer lock ignore
  }

  if (!_globalKeyDownHandler && typeof document.addEventListener === 'function') {
    _globalKeyDownHandler = (e) => {
      if (e.key === 'Escape') {
        closeAnDuongVuongLoreOverlay();
      }
    };
    document.addEventListener('keydown', _globalKeyDownHandler);
  }

  const viewport = modal.querySelector ? modal.querySelector('#adv-content-viewport') : null;
  if (viewport) {
    renderActiveTabContent(viewport);
  }

  return modal;
}

export function closeAnDuongVuongLoreOverlay() {
  if (typeof document === 'undefined') return;

  try {
    advSoundscapeManager?.stopAll?.(600);
  } catch (e) {}

  if (_globalLoreOverlayElement) {
    safeRemove(_globalLoreOverlayElement);
    _globalLoreOverlayElement = null;
  }
  if (_globalKeyDownHandler && typeof document.removeEventListener === 'function') {
    document.removeEventListener('keydown', _globalKeyDownHandler);
    _globalKeyDownHandler = null;
  }
}

// Convenience trigger function
