// Focus camera smoothly on artifacts or realm hotspots
export function focusCameraOnArtifact(artifactKey, camera, controls) {
  if (!camera) return false;
  const conf = getCameraFocusCoords(artifactKey);

  if (camera.position && conf.pos) {
    camera.position.set(conf.pos.x, conf.pos.y, conf.pos.z);
  }
  if (controls && controls.target && conf.look) {
    controls.target.set(conf.look.x, conf.look.y, conf.look.z);
    controls.update?.();
  } else if (camera.lookAt && conf.look) {
    camera.lookAt(conf.look.x, conf.look.y, conf.look.z);
  }
  return true;
}

// Smooth animated camera zoom (1.2s cubic ease-out)
export function smoothFocusCameraOnHotspot(hotspotKey, camera, controls, durationMs = 1200) {
  if (!camera) return false;
  const conf = getCameraFocusCoords(hotspotKey);
  if (!conf) return false;

  const targetPos = conf.pos;
  const targetLook = conf.look;

  // Headless mode or lack of animation loop: jump immediately
  if (typeof requestAnimationFrame === 'undefined' || !camera.position || typeof camera.position.clone !== 'function') {
    return focusCameraOnArtifact(hotspotKey, camera, controls);
  }

  const startPos = camera.position.clone();
  const startLook = controls?.target?.clone ? controls.target.clone() : (camera.position ? camera.position.clone() : null);
  const startTime = (typeof performance !== 'undefined' && performance.now) ? performance.now() : Date.now();

  function animateZoom(currentTime) {
    const elapsed = currentTime - startTime;
    const t = Math.min(1, elapsed / durationMs);
    // Smooth ease-out cubic curve
    const ease = 1 - Math.pow(1 - t, 3);

    camera.position.x = startPos.x + (targetPos.x - startPos.x) * ease;
    camera.position.y = startPos.y + (targetPos.y - startPos.y) * ease;
    camera.position.z = startPos.z + (targetPos.z - startPos.z) * ease;

    if (controls?.target && startLook && targetLook) {
      controls.target.x = startLook.x + (targetLook.x - startLook.x) * ease;
      controls.target.y = startLook.y + (targetLook.y - startLook.y) * ease;
      controls.target.z = startLook.z + (targetLook.z - startLook.z) * ease;
      controls.update?.();
    } else if (camera.lookAt && targetLook) {
      const curX = (startLook?.x || 0) + (targetLook.x - (startLook?.x || 0)) * ease;
      const curY = (startLook?.y || 0) + (targetLook.y - (startLook?.y || 0)) * ease;
      const curZ = (startLook?.z || 0) + (targetLook.z - (startLook?.z || 0)) * ease;
      camera.lookAt(curX, curY, curZ);
    }

    if (t < 1) {
      requestAnimationFrame(animateZoom);
    }
  }

  requestAnimationFrame(animateZoom);
  return true;
}

// ─── Procedural 3D Spatial Audio Soundscape Director ─────────────────────────
export class AnDuongVuongSoundscapeManager {
  constructor() {
    this._audioCtx = null;
    this._activeNodes = [];
    this._isPlaying = false;
    this._buffers = {};
  }

  getAudioContext() {
    if (typeof window === 'undefined') return null;
    const AudioContextClass = window.AudioContext || window.webkitAudioContext;
    if (!AudioContextClass) return null;
    if (!this._audioCtx) {
      try {
        this._audioCtx = new AudioContextClass();
      } catch (e) {
        return null;
      }
    }
    if (this._audioCtx?.state === 'suspended') {
      this._audioCtx.resume?.().catch(() => {});
    }
    return this._audioCtx;
  }

  getProceduralBuffer(kind) {
    const ctx = this.getAudioContext();
    if (!ctx) return null;
    if (this._buffers[kind]) return this._buffers[kind];

    const sampleRate = ctx.sampleRate || 44100;
    let buffer = null;

    if (kind === 'bronze_drum') {
      const duration = 5.0;
      const length = Math.floor(sampleRate * duration);
      buffer = ctx.createBuffer(1, length, sampleRate);
      const data = buffer.getChannelData(0);
      for (let i = 0; i < length; i++) {
        const t = i / sampleRate;
        const tau = t % 2.5;
        const env = Math.exp(-tau * 3.2);
        const attack = Math.exp(-tau * 45.0);
        const f0 = 108.0;
        const fundamental = Math.sin(2.0 * Math.PI * f0 * t) * 0.55;
        const overtone1 = Math.sin(2.0 * Math.PI * f0 * 2.08 * t) * 0.28;
        const overtone2 = Math.sin(2.0 * Math.PI * f0 * 3.15 * t) * 0.16;
        const bellClank = Math.sin(2.0 * Math.PI * 880.0 * t) * attack * 0.22;
        data[i] = (fundamental + overtone1 + overtone2) * env * 0.75 + bellClank;
      }
    } else if (kind === 'crossbow_string') {
      const duration = 3.0;
      const length = Math.floor(sampleRate * duration);
      buffer = ctx.createBuffer(1, length, sampleRate);
      const data = buffer.getChannelData(0);
      let noiseState = 0;
      for (let i = 0; i < length; i++) {
        const t = i / sampleRate;
        if (t < 1.4) {
          const snapPitch = 310.0 + 310.0 * Math.exp(-t * 28.0);
          const stringEnv = Math.exp(-t * 6.2);
          const stringTwang = Math.sin(2.0 * Math.PI * snapPitch * t) * stringEnv * 0.65;
          const white = Math.random() * 2.0 - 1.0;
          noiseState += 0.08 * (white - noiseState);
          const whooshEnv = Math.max(0.0, Math.sin(Math.min(Math.PI, t * 3.5))) * Math.exp(-t * 2.8);
          data[i] = (stringTwang + noiseState * whooshEnv * 0.35) * 0.7;
        } else {
          data[i] = 0.0;
        }
      }
    } else if (kind === 'bamboo_wind') {
      const duration = 5.0;
      const length = Math.floor(sampleRate * duration);
      buffer = ctx.createBuffer(1, length, sampleRate);
      const data = buffer.getChannelData(0);
      let lp = 0;
      for (let i = 0; i < length; i++) {
        const t = i / sampleRate;
        const white = Math.random() * 2.0 - 1.0;
        lp += 0.022 * (white - lp);
        const swell = 0.45 + 0.55 * Math.pow(Math.sin((t / 5.0) * Math.PI * 2.0), 2.0);
        data[i] = lp * swell * 0.55;
      }
    } else if (kind === 'ocean_waves') {
      const duration = 6.0;
      const length = Math.floor(sampleRate * duration);
      buffer = ctx.createBuffer(1, length, sampleRate);
      const data = buffer.getChannelData(0);
      let surfLp = 0;
      for (let i = 0; i < length; i++) {
        const t = i / sampleRate;
        const white = Math.random() * 2.0 - 1.0;
        surfLp += 0.014 * (white - surfLp);
        const tau = t % 3.0;
        const swell = Math.pow(Math.sin((tau / 3.0) * Math.PI), 2.5);
        const crashEnv = Math.exp(-Math.pow(tau - 1.5, 2.0) / 0.3);
        data[i] = (surfLp * swell * 0.6 + white * crashEnv * 0.15) * 0.65;
      }
    }

    if (buffer) {
      this._buffers[kind] = buffer;
    }
    return buffer;
  }

  playSound(kind, loop = false, maxDuration = 8.0) {
    const ctx = this.getAudioContext();
    if (!ctx) return null;
    const buffer = this.getProceduralBuffer(kind);
    if (!buffer) return null;

    try {
      const source = ctx.createBufferSource();
      source.buffer = buffer;
      source.loop = loop;

      const gainNode = ctx.createGain();
      gainNode.gain.setValueAtTime(0.001, ctx.currentTime);
      gainNode.gain.linearRampToValueAtTime(0.65, ctx.currentTime + 0.2);

      if (!loop && maxDuration) {
        gainNode.gain.setValueAtTime(0.65, ctx.currentTime + maxDuration - 0.5);
        gainNode.gain.linearRampToValueAtTime(0.0001, ctx.currentTime + maxDuration);
        source.stop(ctx.currentTime + maxDuration);
      }

      source.connect(gainNode);
      gainNode.connect(ctx.destination);
      source.start();

      this._activeNodes.push({ source, gainNode });
      return source;
    } catch (e) {
      return null;
    }
  }

  toggleSoundscape() {
    if (this._isPlaying) {
      this.stopAll();
      this._isPlaying = false;
    } else {
      this.playSound('bronze_drum', true);
      this.playSound('bamboo_wind', true);
      this.playSound('ocean_waves', true);
      this._isPlaying = true;
    }
    return this._isPlaying;
  }

  stopAll(fadeTimeMs = 600) {
    const ctx = this.getAudioContext();
    const fadeSec = fadeTimeMs / 1000;
    this._activeNodes.forEach(({ source, gainNode }) => {
      try {
        if (ctx && gainNode?.gain) {
          gainNode.gain.setValueAtTime(gainNode.gain.value, ctx.currentTime);
          gainNode.gain.linearRampToValueAtTime(0.0001, ctx.currentTime + fadeSec);
          setTimeout(() => {
            try { source.stop(); } catch (e) {}
          }, fadeTimeMs + 50);
        } else {
          source.stop();
        }
      } catch (e) {}
    });
    this._activeNodes = [];
    this._isPlaying = false;
  }
}

